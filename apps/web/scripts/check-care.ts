import assert from 'node:assert/strict';
import { createApi } from '../src/shared/api/api';
import { createMockTransport, mockControls } from '../src/shared/api/mock/server';
import { buildCareSchedule, parseCareRequest, plantsInZone } from '../src/shared/analytics/careSchedule';
import { buildDrawnZone } from '../src/shared/api/mock/drawnZone';
import { species } from '../src/shared/api/mock/species';
import { DEFAULT_RATES, ratesMap } from '../src/shared/analytics/rates';
import type { Plant } from '../src/shared/api/types';

mockControls.latencyMs = 0;
const api = createApi(createMockTransport());
const site = buildDrawnZone('care-test', 'Care test', [[76.95,52.28],[76.96,52.28],[76.96,52.29],[76.95,52.29],[76.95,52.28]], 60);
const plant: Plant = { id: 'registered', name: 'Test', kind: 'tree', lat: 52.285, lng: 76.955, speciesId: species[0].id, condition: 'unknown', isDemo: true, evidenceIds: [], version: 1 };
const rates = ratesMap(DEFAULT_RATES), at = new Date('2026-12-31T20:00:00Z'); // Jan 1 locally
const empty = buildCareSchedule(site, [], species, rates, { months: 12, crewVisitsPerMonth: 0, budgetKzt: 1 }, at);
assert.equal(empty.tasks.length, 12);
assert.ok(empty.tasks.every(t => t.objectType === 'candidate_site' && t.action === 'inspect' && t.estimatedCostKzt === null && t.requiredWaterLiters === null));
assert.equal(empty.tasks[0].dueAt?.slice(0, 7), '2027-02');
assert.equal(empty.tasks[11].dueAt?.slice(0, 7), '2028-01');
assert.ok(empty.warnings.some(w => w.includes('не проверен')));
assert.ok(empty.warnings.some(w => w.includes('лимите 0')));
const care = buildCareSchedule(site, [plant], species, rates, { months: 12 }, at);
assert.ok(care.tasks.some(t => t.action === 'water'));
assert.ok(care.tasks.every(t => t.objectType === 'plant' && t.objectId === plant.id));
assert.deepEqual(care, buildCareSchedule(site, [plant], species, rates, { months: 12 }, at));
assert.equal(new Set(care.tasks.map(t => t.id)).size, care.tasks.length);
const hole = { ...site, geometry: { type: 'Polygon' as const, coordinates: [site.geometry.type === 'Polygon' ? site.geometry.coordinates[0] : [], [[76.954,52.284],[76.956,52.284],[76.956,52.286],[76.954,52.286],[76.954,52.284]] as [number, number][]] } };
assert.equal(plantsInZone(hole, [plant]).length, 0);
assert.equal(plantsInZone(site, [{ ...plant, lng: 77 }]).length, 0);
const unknown = buildCareSchedule(site, [{ ...plant, speciesId: null, species: null }], species, rates, { months: 12 }, at);
assert.ok(unknown.tasks.every(t => t.action === 'inspect'));
const flower = species.find(s => s.form === 'flower')!;
const flowerCare = buildCareSchedule(site, [{ ...plant, speciesId: flower.id }], species, rates, { months: 12 }, at);
assert.ok(flowerCare.tasks.some(t => t.action === 'weed'));
assert.ok(flowerCare.tasks.filter(t => t.action === 'water').every(t => t.requiredWaterLiters === null));
for (const bad of [{ months: 0 }, { months: 13 }, { months: 1.1 }, { months: '3' }, { months: 1, budgetKzt: -1 }, { months: 1, crewVisitsPerMonth: null }, { months: 1, extra: true }]) assert.throws(() => parseCareRequest(bad));
const zone = (await api.sites()).data[0], plants = (await api.plants()).data;
assert.deepEqual(await api.careSchedule(zone.id, { months: 2 }), buildCareSchedule(zone, plants, species, rates, { months: 2 }));
const draft = (await api.careSchedule(zone.id, { months: 2 })).tasks[0];
const { id: _id, objectName: _name, dataClass: _class, estimatedCostKzt: _cost, ...body } = draft;
const task = await api.createTask(body, 'care-replay');
assert.equal(task.id, (await api.createTask(body, 'care-replay')).id);
await assert.rejects(api.createTask({ ...body, objectType: 'candidate_site', objectId: zone.id, action: 'water' }, 'bad-care'));
mockControls.role = 'viewer';
assert.equal((await api.careSchedule(zone.id, { months: 1 })).method, 'rules');
await assert.rejects(api.createTask(body, 'viewer-care'));
mockControls.role = 'worker';
await assert.rejects(api.careSchedule(zone.id, { months: 1 }));
console.log('Care OK: calendar horizon, holes, plant-only care, missing data, mock parity, validation, roles and replay');
