// Команды интерфейса в чате ассистента: «нарисуй зону» — это просьба включить рисование на карте,
// а не вопрос к расчётам. Такие команды выполняются сразу в браузере, без сервера и модели.
export type UiCommand = 'draw';

// «нарисуй зону», «обведи участок», «начерти контур»; по-казахски — «аймақ сыз», «аймақты сызу».
const DRAW = /(нарис|начерт|обвед|рисова)\S*(\s+\S+){0,3}\s+(зон|участ|контур|полигон|территор)|^(нарисуй|начерти|обведи)\s*[.!]?$|аймақ\S*\s+сыз|сыз\S*\s+аймақ/i;

export function uiCommand(text: string): UiCommand | null {
  return DRAW.test(text.trim()) ? 'draw' : null;
}
