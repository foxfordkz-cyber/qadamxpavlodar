import { z } from 'zod';
import { id,roles,version,uniqueIds } from './core.js';
import { plantInput,catalogInput,resourceInput } from './data.js';
import { taskCreate } from './tasks.js';
import { designCreate } from './designs.js';
import { reportContent } from './reports.js';
import type { Operation } from './router.js';
const object=z.object({}).passthrough();
const date=z.iso.datetime({offset:true});
const user=z.object({id,displayName:z.string(),role:roles,active:z.boolean(),version,profile:object.nullable().optional()}).strict();
const crew=z.object({id,name:z.string(),foremanId:id,active:z.boolean(),resourceIds:uniqueIds,version,members:z.array(object).optional()}).strict();
const task=taskCreate.extend({id,createdAt:date,updatedAt:date,status:z.enum(['draft','assigned','in_progress','submitted','verified']),assignedCrewId:id.nullable(),assignedWorkerIds:uniqueIds,resourceIds:uniqueIds,scheduledStart:date.nullable(),scheduledEnd:date.nullable(),approvedDesignId:id.nullable(),approvedDesignVersion:version.nullable(),latestReportId:id.nullable(),planId:id.nullable(),isDemo:z.boolean(),version}).passthrough();
const report=reportContent.extend({id,taskId:id,authorId:id,contributorIds:uniqueIds,createdAt:date,revision:version,version,reviewStatus:z.enum(['pending','accepted','changes_requested']),reviewerId:id.nullable(),reviewComment:z.string().nullable(),reviewedAt:date.nullable(),idempotencyKey:z.string()}).passthrough();
const design=designCreate.extend({id,revision:version,status:z.enum(['draft','submitted','changes_requested','approved']),version,createdBy:id,checkSnapshot:object,siteVersion:version}).passthrough();
const plant=plantInput.extend({id,version,lastVerifiedCareAt:date.nullable()}).passthrough();
const catalog=z.object(catalogInput.shape).extend({id,version}).passthrough();
const resource=resourceInput.extend({id,version}).passthrough();
const upload=z.object({id,taskId:id,ownerId:id,reportId:id.nullable(),sha256:z.string().regex(/^[0-9a-f]{64}$/),byteSize:z.number().int().positive(),mediaType:z.literal('image/webp'),createdAt:date,contentUrl:z.string()}).strict();
export const responseModels={User:user,Crew:crew,Task:task,Report:report,Design:design,Plant:plant,Catalog:catalog,Resource:resource,Upload:upload};
export function responseData(op:Operation):z.ZodType {
  const p=op.path,m=op.method;
  if(p==='/auth/login')return z.object({user,csrfToken:z.string(),expiresAt:date,mode:z.literal('DEMO')}).strict();
  if(p==='/auth/me')return z.object({user,csrfToken:z.string()}).strict();
  if(p==='/auth/logout')return z.object({loggedOut:z.literal(true)}).strict();
  if(p==='/users'||p==='/users/:id')return m==='get'?z.array(user):user;
  if(p==='/workers')return z.array(user);
  if(p.startsWith('/crews'))return m==='get'?z.array(crew):crew;
  if(p==='/plants/geojson')return z.object({type:z.literal('FeatureCollection'),features:z.array(object)}).strict();
  if(p==='/plants'||p==='/plants/:id')return p==='/plants'&&m==='get'?z.array(plant):plant;
  if(p==='/plant-catalog'||p==='/plant-catalog/:id')return m==='get'?z.array(catalog):catalog;
  if(p==='/resources'||p==='/resources/:id')return m==='get'?z.array(resource):resource;
  if(p==='/tasks'||p==='/tasks/:id'||p==='/tasks/:id/assign'||p==='/tasks/:id/assign-workers'||p==='/tasks/:id/start')return p==='/tasks'&&m==='get'?z.array(task):task;
  if(p==='/designs/:id/create-tasks')return z.array(task);
  if(p==='/designs')return m==='get'?z.array(design):design;
  if(p==='/designs/:id'&&m==='get')return z.union([design,z.object({id,revisions:z.array(design)}).strict()]);
  if(p.startsWith('/designs/')&&!p.endsWith('/visualizations'))return design;
  if(p==='/tasks/:id/reports')return z.object({report,task}).strict();
  if(p==='/reports/:id/review')return z.object({report,task,plants:z.array(plant),careTasks:z.array(task),warnings:z.array(z.string())}).strict();
  if(p==='/reports')return z.array(report);
  if(p==='/reports/:id')return report;
  if(p==='/uploads'&&m==='post')return upload;
  if(p.endsWith('/history')||p.endsWith('/care-history')||(m==='get'&&['/sites','/evidence','/care-policies','/tasks/:id/issues'].includes(p)))return z.array(object);
  return object;
}
